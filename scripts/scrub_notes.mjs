// Produces a publishable copy of project_notes.md.
//
// The original stays exactly as it is: it is Sam's working record, it is
// gitignored, and it has never been pushed. This writes a SECOND file
// with the identities taken out, so the decision record can be shown to
// somebody without taking the roster with it.
//
// Why a separate file rather than an in-place scrub: the private notes
// are more useful with the real names in them -- "the two duplicate
// accounts" is harder to chase than a name -- and an in-place edit is a
// one-way loss of that. Two files, one of which is safe to publish, is
// the same shape as 0010 plus the encrypted archive.
//
//   node scripts/scrub_notes.mjs            # writes project_notes_public.md
//   node scripts/scrub_notes.mjs --check    # reports residue, writes nothing

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const SRC = 'project_notes.md';
const OUT = 'project_notes_public.md';

// THE NAME LIST IS NOT IN THIS FILE, AND THAT IS THE POINT.
//
// The first version of this script carried the 15 names and 6 bib
// numbers inline. Committing it would have published, in the repo, the
// exact data it exists to remove -- the scrubber would have been the
// leak. The list lives in .scrub-names.json, which is gitignored, so
// this file is safe to commit and deliberately useless on its own.
//
// Maintained by hand, not by pattern: a regex for "a capitalised word
// that is a person" cannot tell a first name from a library name, and
// the cost of a miss is somebody's name on the internet. Bib numbers are listed
// explicitly for the mirror reason -- nearly every other four-to-six
// digit number in the notes is a migration id, a cache max-age, a pixel
// value or a CSS colour, and a greedy rule would eat all of them.
const LIST = '.scrub-names.json';
if (!existsSync(LIST)) {
  console.error(`\n  ✗ ${LIST} not found.\n`
    + '    It holds the names and bib numbers to remove and is gitignored\n'
    + '    on purpose, so a fresh clone will not have it. Without it this\n'
    + '    script cannot tell what to scrub, and silently writing an\n'
    + '    unscrubbed "public" file is the one outcome worth refusing.\n');
  process.exit(1);
}
const { people: PEOPLE, bibs: BIBS } = JSON.parse(readFileSync(LIST, 'utf8'));
if (!Array.isArray(PEOPLE) || !PEOPLE.length || !Array.isArray(BIBS)) {
  console.error(`\n  ✗ ${LIST} is malformed -- expected { people: [...], bibs: [...] }\n`);
  process.exit(1);
}

const src = readFileSync(SRC, 'utf8');
let out = src;
const counts = [];

// Longest first, so a full name is replaced before its own first name
// can eat the front of it and leave "Runner C Surname" behind.
const ordered = [...PEOPLE].sort((a, b) => b.length - a.length);
const alias = new Map();
let n = 0;
for (const name of ordered) {
  // A multi-word name and its bare first name share one alias, so the
  // narrative still reads as one person doing two things.
  const first = name.split(' ')[0];
  const key = alias.has(first) ? alias.get(first) : `Runner ${String.fromCharCode(65 + n)}`;
  if (!alias.has(first)) { alias.set(first, key); n++; }
  alias.set(name, key);

  const re = new RegExp(`\\b${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g');
  const hits = (out.match(re) || []).length;
  if (hits) { out = out.replace(re, key); counts.push([name.length, hits]); }
}

// LEADING-ZERO VARIANTS ARE NOT OPTIONAL, and missing them published a
// real bib. A word-bounded match on a bare number does not match inside
// its own zero-padded form -- `\b1234\b` finds nothing in "01234",
// because there is no word boundary between the 0 and the 1 -- so the
// replacement never fires, AND a residue check written with the same
// pattern never notices. The bug and the test for the bug share one
// blind spot.
//
// It is the exact thing lib/validate.ts canonicalises against: the
// padded and bare forms are one bib to a person and two to a raw string
// comparison. Longest first, so the padded form is replaced before the
// bare form can match its tail.
//
// The example above is invented, deliberately. The first version of
// this comment used the real number -- putting the bib back into the
// repository inside the note explaining how it escaped, and making this
// the third time in this project that a tool carried the very data it
// exists to remove.
const bibForms = BIBS.flatMap(b => [`00${b}`, `0${b}`, b]);

let bibHits = 0;
for (const bib of bibForms) {
  const re = new RegExp(`\\b${bib}\\b`, 'g');
  const hits = (out.match(re) || []).length;
  bibHits += hits;
  out = out.replace(re, '9xxxx');
}

const header = `<!-- PUBLISHABLE COPY. Generated by scripts/scrub_notes.mjs from the
     private project_notes.md: ${counts.length} personal names replaced with stable
     aliases and ${bibHits} bib numbers removed. A name plus a bib is a
     lookup key on NYRR results; neither survives here. Do not edit this
     file by hand -- edit the source and regenerate. -->\n\n`;

// Residue check over the text that would actually be written.
const residue = [];
for (const name of PEOPLE) {
  if (new RegExp(`\\b${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`).test(out)) residue.push('name');
}
for (const bib of bibForms) if (new RegExp(`\\b${bib}\\b`).test(out)) residue.push('bib');
if (residue.length) {
  console.error(`\n  ✗ ${residue.length} item(s) survived the scrub\n`);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  console.log('\n  check only — nothing written. No residue found.\n');
  process.exit(0);
}

writeFileSync(OUT, header + out);
console.log(`\n  ${OUT} written  (${(out.length / 1024).toFixed(0)} KB)`);
console.log(`    names replaced   ${counts.length} distinct, ${counts.reduce((s, [, h]) => s + h, 0)} mentions`);
console.log(`    bib numbers      ${bibHits} removed`);
console.log(`    residue          none\n`);
